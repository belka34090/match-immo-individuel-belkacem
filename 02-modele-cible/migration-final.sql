-- ============================================================
-- 29. REGLES NON ENFORCEES PAR UNE SIMPLE CONTRAINTE DE TABLE
-- ============================================================
--
-- Certaines regles du MCD / des regles de gestion necessitent
-- un controle transactionnel, un trigger ou la couche applicative :
--
-- - une DEMANDE doit toujours posseder au moins une VERSION_DEMANDE ;
-- - une VERSION_DEMANDE doit cibler au moins un SECTEUR ;
-- - un BAREME_COMMISSION doit contenir au moins une TRANCHE_COMMISSION ;
-- - un mandat exclusif actif doit bloquer les autres mandats actifs
--   incompatibles pour la meme demande ;
-- - les periodes de baremes d'un meme chasseur ne doivent pas rendre
--   le bareme applicable ambigu ;
-- - les tranches d'un meme bareme ne doivent pas se chevaucher ;
-- - le CLIENT et le CHASSEUR d'un mandat doivent rester coherents avec
--   la demande et son affectation ;
-- - le CHASSEUR d'une commission, sa tranche, son bareme et sa facture
--   doivent rester coherents entre eux ;
-- - la somme des paiements effectues d'une facture ne doit pas depasser
--   le montant a regler ;
-- - certaines chronologies inter-tables (presentation, visite, offre,
--   acte, facture, paiement) necessitent un controle transverse.
--
-- Ces regles seront couvertes par les controles applicatifs,
-- les triggers si necessaires et le plan de tests.
-- ============================================================

